// Typed API client (M14.A2): TypeScript types generated from each service's OpenAPI document.
//
//   npm run api:fetch   saves /openapi/v1.json of every running service into openapi/ (stack must be up)
//   npm run api:types   regenerates src/lib/api-types/*.ts from openapi/*.json
//   npm run api:check   fails if src/lib/api-types is not what openapi/*.json generates (part of npm run check)
//
// The documents are committed, so the types can be rebuilt and checked without the services running.
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const documents = path.join(root, "openapi");
const output = path.join(root, "src", "lib", "api-types");

/** Service → its local port (README, "Service Ports"). */
export const services = {
  identity: 5101,
  ledger: 5102,
  payments: 5103,
  bills: 5104,
  topups: 5105,
  agents: 5106,
  fraud: 5107,
  notifications: 5108,
  reconciliation: 5109,
};

const header = (service) =>
  `// Generated by scripts/api-types.mjs from openapi/${service}.json. Do not edit: run \`npm run api:types\`.\n\n`;

async function fetchDocuments() {
  await mkdir(documents, { recursive: true });
  for (const [service, port] of Object.entries(services)) {
    const host = process.env.WALLETPK_API_HOST ?? "localhost";
    const response = await fetch(`http://${host}:${port}/openapi/v1.json`);
    if (!response.ok) throw new Error(`${service}: ${response.status} from port ${port}. Is the stack running?`);
    const document = await response.json();
    await writeFile(path.join(documents, `${service}.json`), JSON.stringify(document, null, 2) + "\n");
    console.log(`openapi/${service}.json: ${Object.keys(document.paths ?? {}).length} paths`);
  }
}

async function generate(service) {
  const document = JSON.parse(await readFile(path.join(documents, `${service}.json`), "utf8"));
  const ast = await openapiTS(document, { alphabetize: true, exportType: true });
  return header(service) + astToString(ast);
}

async function writeTypes() {
  await mkdir(output, { recursive: true });
  for (const service of await documentNames()) {
    await writeFile(path.join(output, `${service}.ts`), await generate(service));
    console.log(`src/lib/api-types/${service}.ts`);
  }
}

async function checkTypes() {
  const stale = [];
  for (const service of await documentNames()) {
    const expected = await generate(service);
    const actual = await readFile(path.join(output, `${service}.ts`), "utf8").catch(() => null);
    if (actual?.replace(/\r\n/g, "\n") !== expected) stale.push(service);
  }
  if (stale.length > 0) {
    console.error(`API types out of date for: ${stale.join(", ")}. Run \`npm run api:types\`.`);
    process.exit(1);
  }
  console.log("API types match the OpenAPI documents.");
}

async function documentNames() {
  return (await readdir(documents)).filter((name) => name.endsWith(".json")).map((name) => name.slice(0, -5)).sort();
}

const command = process.argv[2];
if (command === "fetch") await fetchDocuments();
else if (command === "types") await writeTypes();
else if (command === "check") await checkTypes();
else {
  console.error("Usage: node scripts/api-types.mjs fetch|types|check");
  process.exit(2);
}
